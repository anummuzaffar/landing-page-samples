    var nodes = [];
    var current = "de";

    function collect(root) {
        var walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, {
            acceptNode: function (node) {
                var p = node.parentNode;
                if (!p) return NodeFilter.FILTER_REJECT;
                var tag = p.nodeName;
                if (tag === "SCRIPT" || tag === "STYLE" || tag === "SVG") return NodeFilter.FILTER_REJECT;
                if (!node.nodeValue || !node.nodeValue.trim()) return NodeFilter.FILTER_REJECT;
                return NodeFilter.FILTER_ACCEPT;
            }
        });
        var n;
        while ((n = walker.nextNode())) {
            nodes.push({ node: n, de: n.nodeValue });
        }
        document.querySelectorAll("option").forEach(function (o) {
            nodes.push({ node: o, de: o.textContent, isOption: true });
        });
    }

    function apply(lang) {
        current = lang === "en" ? "en" : "de";
        document.documentElement.setAttribute("lang", current);
        nodes.forEach(function (item) {
            var raw = item.de;
            var key = raw.trim();
            if (current === "en" && Object.prototype.hasOwnProperty.call(EN, key)) {
                var lead = raw.slice(0, raw.indexOf(key));
                if (/^[.,;:!?]/.test(EN[key])) lead = lead.replace(/\s+$/, "");
                var tail = raw.slice(raw.indexOf(key) + key.length);
                var value = lead + EN[key] + tail;
                if (item.isOption) item.node.textContent = value;
                else item.node.nodeValue = value;
            } else {
                if (item.isOption) item.node.textContent = raw;
                else item.node.nodeValue = raw;
            }
        });
        document.dispatchEvent(new CustomEvent("inv:lang", { detail: { lang: current } }));
    }

    function t(key) {
        if (current === "en" && Object.prototype.hasOwnProperty.call(EN, key)) return EN[key];
        return key;
    }

    function locale() {
        return current === "en" ? "en-US" : "de-DE";
    }

    document.addEventListener("DOMContentLoaded", function () {
        collect(document.body);
        var m = /[?&]lang=([a-z]{2})/i.exec(window.location.search);
        if (m && m[1].toLowerCase() === "en") apply("en");
    });

    return { apply: apply, t: t, locale: function () { return locale(); }, lang: function () { return current; } };
